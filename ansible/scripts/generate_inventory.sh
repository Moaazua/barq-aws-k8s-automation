#!/usr/bin/env bash
# Generates ansible/inventory/hosts.ini from `terraform output -json`.
#
# Usage:   ./scripts/generate_inventory.sh
# Options (environment variables):
#   TF_DIR        Terraform root dir   (default: ../terraform/root, relative to ansible/)
#   BARQ_SSH_KEY  Path to the .pem key (default: ~/.ssh/barq-k8s-key.pem)
#   SSH_USER      Remote user          (default: ubuntu)
set -euo pipefail

ANSIBLE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TF_DIR="${TF_DIR:-$ANSIBLE_DIR/../terraform/root}"
KEY="${BARQ_SSH_KEY:-$HOME/.ssh/barq-k8s-key.pem}"
SSH_USER="${SSH_USER:-ubuntu}"
OUT="$ANSIBLE_DIR/inventory/hosts.ini"

command -v terraform >/dev/null || { echo "ERROR: terraform not found in PATH" >&2; exit 1; }
command -v jq        >/dev/null || { echo "ERROR: jq not found (install it: sudo dnf/apt install -y jq)" >&2; exit 1; }
[ -d "$TF_DIR" ] || { echo "ERROR: Terraform dir not found: $TF_DIR (set TF_DIR)" >&2; exit 1; }

JSON="$(terraform -chdir="$TF_DIR" output -json)"

get() {
  local v
  v="$(printf '%s' "$JSON" | jq -r --arg k "$1" '.[$k].value // empty')"
  if [ -z "$v" ]; then
    echo "ERROR: Terraform output '$1' is missing. Add it to terraform/root/outputs.tf, run 'terraform apply', then retry." >&2
    exit 1
  fi
  printf '%s' "$v"
}

CP_PUB="$(get control_plane_public_ip)"
CP_PRIV="$(get control_plane_private_ip)"
W_PUB="$(get worker_public_ip)"
W_PRIV="$(get worker_private_ip)"

cat > "$OUT" <<INV
# GENERATED by scripts/generate_inventory.sh from Terraform outputs. Do not commit.
[control_plane]
k8s-master  ansible_host=${CP_PUB}  private_ip=${CP_PRIV}

[workers]
k8s-worker1 ansible_host=${W_PUB}  private_ip=${W_PRIV}

[k8s:children]
control_plane
workers

[k8s:vars]
ansible_user=${SSH_USER}
ansible_ssh_private_key_file=${KEY}
INV

echo "Inventory written to $OUT"
cat "$OUT"
